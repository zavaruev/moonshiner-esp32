#!/usr/bin/env python3
"""Embed moonshiner_ui_v24.js into a C header, compressed at build time.

The UI is ~70 KB. Sending it uncompressed over the ESP32's lossy WiFi link is
slow, so both raw and gzip bytes are compiled in and the server picks based on
Accept-Encoding. Run inside the ESP-IDF container:
    python3 tools/embed_web.py
"""
import gzip
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SRC = os.path.join(ROOT, "moonshiner_ui_v24.js")
OUT = os.path.join(ROOT, "main", "ui_assets.h")


def array(name, data):
    lines = ["static const unsigned char %s[] = {" % name]
    for i in range(0, len(data), 16):
        lines.append("    " + ",".join("0x%02x" % b for b in data[i:i + 16]) + ",")
    lines.append("};")
    lines.append("static const size_t %s_len = %d;" % (name, len(data)))
    return "\n".join(lines)


def main():
    with open(SRC, "rb") as fh:
        raw = fh.read()
    packed = gzip.compress(raw, 9)
    header = (
        "#pragma once\n"
        "#include <stddef.h>\n\n"
        "/* Generated by tools/embed_web.py from moonshiner_ui_v24.js. Do not edit. */\n\n"
        + array("ui_js_raw", raw)
        + "\n\n"
        + array("ui_js_gzip", packed)
        + "\n"
    )
    with open(OUT, "w", encoding="ascii") as fh:
        fh.write(header)
    print("%s: raw %d bytes, gzip %d bytes" % (OUT, len(raw), len(packed)))


if __name__ == "__main__":
    main()
